// Validate the installer/update manifest as one release before anything becomes public.
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const assert = require('node:assert/strict')
const yaml = require('js-yaml')
const root = path.join(__dirname, '..')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))
const dist = path.join(root, 'dist')
const installerName = 'AIHub-DJ-Setup.exe'
const installer = fs.readFileSync(path.join(dist, installerName))
assert.equal(installer.subarray(0, 2).toString(), 'MZ', 'Installer must be a Windows executable')
const manifest = yaml.load(fs.readFileSync(path.join(dist, 'latest.yml'), 'utf8'))
assert.equal(manifest.version, pkg.version, 'Update manifest version must match package version')
const file = manifest.files?.find(item => item.url === installerName)
assert.ok(file, 'Manifest must point to the stable installer filename')
assert.equal(file.size, installer.length, 'Manifest installer size mismatch')
const sha512 = crypto.createHash('sha512').update(installer).digest('base64')
assert.equal(file.sha512, sha512, 'Installer checksum mismatch')
if (manifest.sha512) assert.equal(manifest.sha512, sha512)
if (manifest.path) assert.equal(manifest.path, installerName)
assert.ok(fs.statSync(path.join(dist, installerName + '.blockmap')).size > 0, 'Differential update blockmap is required')
const provider = yaml.load(fs.readFileSync(path.join(dist, 'win-unpacked/resources/app-update.yml'), 'utf8'))
assert.equal(provider.provider, 'github')
assert.equal(provider.owner, 'pitchiluxe')
assert.equal(provider.repo, 'aihub-dj')
const asar = require('@electron/asar')
const archive = path.join(dist, 'win-unpacked/resources/app.asar')
const packaged = JSON.parse(asar.extractFile(archive, 'package.json').toString())
assert.equal(packaged.version, pkg.version, 'Packaged app version mismatch')
const main = asar.extractFile(archive, path.join('out', 'main', 'index.js')).toString()
const preload = asar.extractFile(archive, path.join('out', 'preload', 'index.js')).toString()
assert.ok(main.includes('updater:getState') && main.includes('update-available'), 'Packaged app must contain the updater')
assert.ok(preload.includes('updater:getState'), 'Packaged app must expose its update bridge')
const outPrefix = path.sep + 'out' + path.sep
assert.ok(asar.listPackage(archive).filter(name => name.startsWith(outPrefix)).every(name =>
  ['main', 'preload', 'renderer'].some(folder => name === outPrefix + folder || name.startsWith(outPrefix + folder + path.sep))
), 'Test output or preview data leaked into the packaged app')
const sha256 = crypto.createHash('sha256').update(installer).digest('hex')
fs.writeFileSync(path.join(dist, 'SHA256SUMS.txt'), `${sha256}  ${installerName}\n`)
console.log(`Verified AIHub DJ ${pkg.version}: installer, blockmap, latest.yml checksum and embedded GitHub update feed.`)
console.log(`SHA256 ${sha256}`)
